# frozen_string_literal: true

# Generates the Mermaid ERD for NLO-owned tables from live Rails reflections, so the exported diagram follows the
# schema instead of a hand-kept snapshot. Run through `bin/export_diagrams` (container harness, then rendering).
#
# Output: docs/diagrams/source/nlo_regions_schema_erd.mmd and docs/diagrams/reference/nlo_schema_inventory.md

# Diagram file name => the models drawn in it.
DIAGRAMS = {
  'nlo_regions_schema_erd' => %w[BetterTogether::Geography::State BetterTogether::Geography::Region
                                 NewfoundlandLabradorOnline::RegionVersion
                                 NewfoundlandLabradorOnline::RegionIdentifier],
  'nlo_settlements_schema_erd' => %w[BetterTogether::Geography::State BetterTogether::Geography::Settlement
                                     BetterTogether::Geography::SettlementStatus
                                     BetterTogether::Geography::SettlementIdentifier],
  'nlo_elections_schema_erd' => %w[BetterTogether::Geography::State BetterTogether::Geography::Region
                                   NewfoundlandLabradorOnline::Election
                                   NewfoundlandLabradorOnline::ElectoralContest NewfoundlandLabradorOnline::Candidacy
                                   NewfoundlandLabradorOnline::PoliticalParty],
  'nlo_civic_roles_schema_erd' => %w[BetterTogether::Community BetterTogether::PersonCommunityMembership
                                     NewfoundlandLabradorOnline::MembershipMandate
                                     NewfoundlandLabradorOnline::CommunitySeat
                                     NewfoundlandLabradorOnline::SeatBoundary
                                     NewfoundlandLabradorOnline::CommunityAssociation
                                     NewfoundlandLabradorOnline::LegislatureDetail]
}.freeze

TYPE_MAP = { 'uuid' => 'uuid', 'string' => 'string', 'text' => 'text', 'integer' => 'int', 'date' => 'date',
             'datetime' => 'datetime', 'boolean' => 'bool', 'float' => 'float' }.freeze

def entity_name(klass) = klass.table_name.upcase

def column_key(name)
  return ' PK' if name == 'id'

  name.end_with?('_id') ? ' FK' : ''
end

def column_lines(klass)
  klass.columns.map do |column|
    type = TYPE_MAP.fetch(column.sql_type_metadata.type.to_s, column.sql_type_metadata.type.to_s.gsub(/\W/, '_'))
    key = column_key(column.name)
    "    #{type} #{column.name}#{key}"
  end
end

def relationship_lines(classes)
  classes.flat_map do |klass|
    owned = klass.reflect_on_all_associations(:has_many) + klass.reflect_on_all_associations(:has_one)
    owned.filter_map do |reflection|
      target = association_target(reflection)
      next unless target && classes.include?(target)

      arrow = reflection.macro == :has_one ? 'o|' : 'o{'
      "  #{entity_name(klass)} ||--#{arrow} #{entity_name(target)} : \"#{reflection.name}\""
    end
  end
end

def association_target(reflection)
  reflection.klass
rescue NameError
  nil
end

def erd_for(classes)
  erd = ['%% Generated by scripts/export_diagrams.rb. Do not edit by hand.', '%% render.orientation: landscape',
         'erDiagram']
  classes.each do |klass|
    erd << "  #{entity_name(klass)} {"
    erd.concat(column_lines(klass))
    erd << '  }'
  end
  erd.concat(relationship_lines(classes))
  "#{erd.join("\n")}\n"
end

drawn = DIAGRAMS.transform_values { |names| names.map(&:constantize) }
drawn.each do |file, classes|
  File.write(Rails.root.join("docs/diagrams/source/#{file}.mmd"), erd_for(classes))
end

classes = drawn.values.flatten.uniq
inventory = ['# NLO schema inventory', '', 'Generated by `scripts/export_diagrams.rb`.', '']
classes.each do |klass|
  inventory.push("## `#{klass.table_name}` (#{klass.name})", '')
  klass.columns.each { |c| inventory << "- `#{c.name}` #{c.sql_type}#{' NOT NULL' unless c.null}" }
  inventory << ''
end
File.write(Rails.root.join('docs/diagrams/reference/nlo_schema_inventory.md'), inventory.join("\n"))
puts "wrote #{drawn.size} diagrams, #{classes.size} entities"
